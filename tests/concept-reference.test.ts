import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';import os from 'node:os';import path from 'node:path';import {createHash} from 'node:crypto';
import {Store} from '../engine/store';import {Engine} from '../engine/engine';import {WorkbenchEngine} from '../engine/workbench';
import {ChromeWorkbenchRunner} from '../electron/chrome-workbench-runner';import {routeExternalRunners} from '../engine/runway-workbench-runner';
import type {WorkbenchExecutionContext} from '../shared/workbench';
const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLbtAAAAABJRU5ErkJggg==','base64');
test('imported concept is frozen as a reference; empty stopped job closes only before native submission',async t=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'ps-concept-ref-')),store=new Store(root);
  await store.open(path.resolve('node_modules/sql.js/dist/sql-wasm.wasm'));
  const p=new Engine(store,{} as any).create('Synthetic reference handoff');
  store.write(p.id,'assets/source.png',png);p.assets.push({id:'source',file:'assets/source.png',kind:'image',label:'Character'} as any);store.save(p);
  const journalRoot=path.join(root,'journals');
  const chrome=new ChromeWorkbenchRunner({journalRoot,bridgePath:'unused',projectRoot:()=>store.directory(p.id),blenderPath:()=>'',downloadsPath:path.join(root,'downloads')});
  const captured:WorkbenchExecutionContext[]=[];
  chrome.run=async ctx=>{captured.push(ctx);return {status:'needs_input',summary:'Explicit test stub, no submission',threadId:'test-only',usage:undefined};};
  const engine=new WorkbenchEngine(store,{execute:async()=>{throw Error('Unexpected worker');}},{externalRunner:routeExternalRunners(chrome,chrome)});
  t.after(()=>{engine.shutdown();store.db.close();fs.rmSync(root,{recursive:true,force:true});});
  let w=engine.action(p.id,{kind:'import-source',assetId:'source'});
  const source=w.jobs[0],selection=structuredClone(w.selections.concept),original=source.candidates[0].artifacts[0];
  const request={step:'concept' as const,provider:'gpt' as const,executionMode:'codex-app' as const,prompt:'이 캐릭터에 어울리는 대검만 생성',generationCount:2,conceptMode:'reference' as const,baseJobId:source.id,baseCandidateId:selection.candidateId};
  const approval={accepted:true,studioCreditLimit:0,imageCreditLimit:0};
  assert.throws(()=>engine.action(p.id,{kind:'execute',request:{...request,baseJobId:undefined},approval}),/참고할 이미지/);
  assert.throws(()=>engine.action(p.id,{kind:'execute',request:{...request,baseCandidateId:'wrong'},approval}),/하나의 결과/);
  const empty={...request,conceptMode:'design' as const,baseJobId:undefined,baseCandidateId:undefined};
  const old=engine.action(p.id,{kind:'execute',request:empty,approval}).jobs[0];await engine.wait(w.id);
  assert.equal(captured[0].inputs.length,0);
  const journal=path.join(journalRoot,w.id,old.id+'.json');fs.mkdirSync(path.dirname(journal),{recursive:true});
  const blocked={jobId:old.id,requestHash:old.externalExecution!.requestHash,entries:[{phase:'images',state:'reserved',cost:0}]};
  fs.writeFileSync(journal,JSON.stringify(blocked));
  assert.throws(()=>engine.action(p.id,{kind:'external-close-empty-concept',jobId:old.id}),/제출/);
  fs.writeFileSync(journal,JSON.stringify({...blocked,entries:[]}));
  engine.action(p.id,{kind:'external-close-empty-concept',jobId:old.id});
  const next=engine.action(p.id,{kind:'execute',request,approval}).jobs[0];await engine.wait(w.id);
  assert.equal(captured.length,2);assert.deepEqual(captured[1].inputs,[original]);
  assert.deepEqual(captured[1].job.dependencies,{}); // no self-slot invalidation on adopting new output
  const packet=JSON.parse(fs.readFileSync(path.join(captured[1].workspace,'external-request.json'),'utf8'));
  assert.equal(packet.inputs[0].sha256,original.sha256);assert.equal(packet.request.baseCandidateId,selection.candidateId);
  assert.deepEqual(engine.getForProject(p.id)!.selections.concept,selection);
  assert.equal(createHash('sha256').update(fs.readFileSync(store.file(p.id,original.path))).digest('hex'),original.sha256);
  assert.throws(()=>engine.action(p.id,{kind:'external-close-empty-concept',jobId:next.id}),/참조 없이/);
  const prompt=(chrome as any).prompt(captured[1],packet,{entries:[]});
  assert.match(prompt,/attach that exact file to the ChatGPT composer/);assert.match(prompt,/not another full-body character/);
  // Stop test-only reference job, then verify plain text mode remains reference-free.
  engine.action(p.id,{kind:'external-cancel',jobId:next.id});
  // Missing/changed source is rejected before a new dispatch.
  const context=captured[1];fs.appendFileSync(store.file(p.id,original.path),'tampered');
  assert.throws(()=>engine.action(p.id,{kind:'external-run',jobId:next.id}),/중지|실행|대기|변경|작업/);
  assert.equal(captured.length,2);assert.equal(context.job.request.conceptMode,'reference');
});
